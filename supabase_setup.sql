create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  created_at timestamptz not null default now()
);

create or replace function public.make_profile()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  wanted text;
  candidate text;
begin
  wanted := coalesce(new.raw_user_meta_data->>'username', new.raw_user_meta_data->>'full_name', 'cook');
  wanted := lower(regexp_replace(wanted, '[^a-zA-Z0-9_]', '', 'g'));
  wanted := left(wanted, 18);
  if length(wanted) < 3 then wanted := 'cook'; end if;
  candidate := wanted;
  if exists(select 1 from public.profiles where username = candidate) then
    candidate := left(wanted, 14) || '_' || substr(replace(new.id::text,'-',''),1,8);
  end if;
  insert into public.profiles(id, username) values(new.id, candidate)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.make_profile();

create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 90),
  original_dish text default '',
  description text default '',
  ingredients text not null,
  steps text not null,
  image_url text not null,
  image_path text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.likes (
  recipe_id bigint not null references public.recipes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(recipe_id,user_id)
);

alter table public.profiles enable row level security;
alter table public.recipes enable row level security;
alter table public.likes enable row level security;

drop policy if exists "Profiles are public" on public.profiles;
create policy "Profiles are public" on public.profiles for select using (true);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update using (auth.uid()=id) with check (auth.uid()=id);

drop policy if exists "Recipes are public" on public.recipes;
create policy "Recipes are public" on public.recipes for select using (true);
drop policy if exists "Signed-in users create recipes" on public.recipes;
create policy "Signed-in users create recipes" on public.recipes for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Owners update recipes" on public.recipes;
create policy "Owners update recipes" on public.recipes for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "Owners delete recipes" on public.recipes;
create policy "Owners delete recipes" on public.recipes for delete to authenticated using (auth.uid()=user_id);

drop policy if exists "Likes are public" on public.likes;
create policy "Likes are public" on public.likes for select using (true);
drop policy if exists "Users like as themselves" on public.likes;
create policy "Users like as themselves" on public.likes for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Users remove own likes" on public.likes;
create policy "Users remove own likes" on public.likes for delete to authenticated using (auth.uid()=user_id);

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('recipe-images','recipe-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp'];

drop policy if exists "Recipe images are public" on storage.objects;
create policy "Recipe images are public" on storage.objects for select using (bucket_id='recipe-images');
drop policy if exists "Members upload own recipe images" on storage.objects;
create policy "Members upload own recipe images" on storage.objects for insert to authenticated with check (bucket_id='recipe-images' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "Members delete own recipe images" on storage.objects;
create policy "Members delete own recipe images" on storage.objects for delete to authenticated using (bucket_id='recipe-images' and (storage.foldername(name))[1]=auth.uid()::text);

-- Helpful indexes
create index if not exists recipes_created_at_idx on public.recipes(created_at desc);
create index if not exists recipes_user_id_idx on public.recipes(user_id);
create index if not exists likes_recipe_id_idx on public.likes(recipe_id);
